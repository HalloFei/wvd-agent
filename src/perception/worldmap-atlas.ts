/**
 * The world map, stored.
 *
 * Everything here was measured on the live 1920x1080 window on 2026-11-01 (docs/status.md, "The
 * world map, stored"), not read out of the game's files:
 *
 * - the map is drawn in a 960x1080 strip at x=480, with black pillars either side and the zoom
 *   legend on the right pillar;
 * - at max zoom-out the whole map is **1360x1496** atlas pixels: it pans at most ~400 px
 *   horizontally and ~416 px vertically, so it is one and a bit screens in each direction;
 * - zoom is discrete, **max zoom-out .. 3 steps .. max zoom-in**, about 1.34x content per step;
 * - a drag moves the map 2.05-2.48 px per px of pointer travel (the gain varies with the clamp), so
 *   a navigator pans, re-locates and corrects rather than trusting one open-loop drag;
 * - the label banners are screen-space art at every zoom: one matched banner anchors the view, and
 *   the anchor is what turns this table into a screen point for any other site;
 * - at max zoom-out the game culls colliding labels — 北穿幽冥城 is one of the culled ones — while
 *   its icon is still drawn, at about 0.45 of the legacy art's size, and still matches.
 *
 * The atlas image and the label crops are `testdata/worldmap/2026-11-01/overview.jpg` and
 * `src/perception/worldmap-labels.ts` (generated by `scripts/extract-worldmap-labels.mjs`).
 */
import { WORLD_MAP_LABELS, type WorldMapLabel } from './worldmap-labels.ts';

/** The atlas's own pixel size, with its top-left corner as the origin. */
export const WORLD_MAP_SIZE = { width: 1_360, height: 1_496 } as const;

/** Where the game draws the map: a portrait strip between the black pillars. */
export const MAP_STRIP = { x: 480, y: 0, width: 960, height: 1_080 } as const;

/** The measured zoom ladder: max-out, then three steps in, 1.34x each. */
export const MAP_ZOOM = { steps: 3, stepScale: 1.34 } as const;

/** The legacy node art is drawn at this fraction of its native size at max zoom-out. */
export const NODE_ICON_SCALE_AT_MAX_OUT = 0.45;

/** The label banner's top sits this many screen pixels above the node's clickable centre. */
export const LABEL_RISE_PX = 40;

/**
 * The map moves this many pixels per pixel of drag. It is a nominal value only: measured runs gave
 * 2.05 (a 100 px drag) and 2.05-2.48 (trimmed drags), so a navigator measures the result of its
 * own pan and corrects instead of trusting the constant.
 */
export const MAP_PAN_GAIN = 2.2;

/** The zoom keys: Q 缩小, E 放大 (the same scans the world-map action uses). */
export const MAP_ZOOM_KEYS = { out: 0x10, in: 0x12 } as const;

/** Where a tap cannot land on a node: the bottom band carries −/+/关闭 and their labels. */
export const SAFE_TAP = { x: 500, y: 40, width: 920, height: 860 } as const;

export type SiteKind = 'city' | 'village' | 'dungeon' | 'trial' | 'shrine' | 'region' | 'ruin';

export interface WorldMapSite {
  readonly id: string;
  /** The Chinese label the game draws. */
  readonly label: string;
  readonly kind: SiteKind;
  /** The click point on the atlas: the node icon's centre. */
  readonly x: number;
  readonly y: number;
  /** The label banner's rectangle on the atlas, when the game draws it at max zoom-out. */
  readonly labelBand?: { readonly x: number; readonly y: number; readonly width: number; readonly height: number };
  /** A `LOCATIONS` id whose icon art confirms this site at max zoom-out. */
  readonly templateId?: string;
}

