const SITES_BY_ID: ReadonlyMap<string, WorldMapSite> = new Map(WORLD_MAP_SITES.map((site) => [site.id, site]));

export function siteById(id: string): WorldMapSite | null {
  return SITES_BY_ID.get(id) ?? null;
}

/** The site's position as a fraction of the map, top-left corner as origin. */
export function relativeOf(site: WorldMapSite): { x: number; y: number } {
  return { x: site.x / WORLD_MAP_SIZE.width, y: site.y / WORLD_MAP_SIZE.height };
}

/** A label template (screen-space art) and the atlas point its top-left sits on. */
export interface LabelAnchor {
  readonly id: string;
  readonly template: { readonly width: number; readonly height: number; readonly gray: Uint8Array };
  readonly at: { readonly x: number; readonly y: number };
}

/** The label banners as match templates, one per site whose label the game draws at max-out. */
export const LABEL_ANCHORS: readonly LabelAnchor[] = Object.entries(WORLD_MAP_LABELS).map(([id, raw]: [string, WorldMapLabel]) => ({
  id,
  template: { width: raw.width, height: raw.height, gray: Uint8Array.from(Buffer.from(raw.gray, 'base64')) },
  at: { x: raw.at.x, y: raw.at.y },
}));

/**
 * The atlas offset of a view, from one matched label: every atlas point p appears on screen at
 * `p - offset` at max zoom-out. The match's top-left and the banner's atlas top-left give it
 * directly, because both crops are the same screen-size art.
 */
export function offsetFromMatch(anchor: LabelAnchor, matchedAt: { x: number; y: number }): { x: number; y: number } {
  return { x: anchor.at.x - matchedAt.x, y: anchor.at.y - matchedAt.y };
}

/** The screen point (strip coordinates) of a site in a view with this atlas offset. */
export function screenPointOf(site: WorldMapSite, offset: { x: number; y: number }): { x: number; y: number } {
  return { x: site.x - offset.x, y: site.y - offset.y };
}

/** Whether a strip point is inside the area a tap may use. */
export function insideSafeTap(point: { x: number; y: number }): boolean {
  return point.x >= SAFE_TAP.x
    && point.x <= SAFE_TAP.x + SAFE_TAP.width
    && point.y >= SAFE_TAP.y
    && point.y <= SAFE_TAP.y + SAFE_TAP.height;
}

/** The horizontal drag that moves the view's content by `delta` pixels (positive = content right). */
export function panDragFor(delta: number): number {
  return Math.round(Math.max(-480, Math.min(480, delta / MAP_PAN_GAIN)));
}
