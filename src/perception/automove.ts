/**
 * The 自動移動 element: the pill the dungeon map raises above the cell a pointer-mode tap selected.
 *
 * Measured live 2026-11-02 (1920x1080, 第四区-城内2F深处-, party at X:21 Y:1). A tap at (1248,766) on
 * the cell north of the party raised the pill over (1182,672)-(1322,706): its glyph sits 36 px left
 * of the tap and 78 px above it, and clicking the glyph walked the party.
 *
 * A tap on the chest cell at (924,154) raised nothing. The 81 px rise would put the pill on the
 * panel's title bar, and that cell is 18 rows up the map — the cell is not walkable from where the
 * party stands, which is exactly the case the walk has to name instead of tapping blind.
 *
 * The template is that glyph (28x28 at (1198,676) on the frame), generated by
 * `scripts/extract-automove-template.ts`. It scores 1.0 on the frame that carries the pill and at
 * most 0.28 on a map frame with none, so 0.7 is a wide floor. The element is screen-space art — it
 * does not scale with the map zoom — so it is matched at scale 1.
 */
import type { PixelRect, Point, RgbaImage } from '../contracts.ts';
import { AUTO_MOVE_GLYPH_BASE64 } from './automove-template.ts';
import { findTemplate, type MatchTemplate } from './match.ts';

/** The glyph at the pill's left: a white circle with the auto-move arrow, 28x28 at (1198,676). */
export const AUTO_MOVE_TEMPLATE: MatchTemplate = {
  width: 28,
  height: 28,
  gray: Uint8Array.from(Buffer.from(AUTO_MOVE_GLYPH_BASE64, 'base64')),
};

/** The floor the live frames support: the element scores 1.0, a map frame with none at most 0.28. */
export const AUTO_MOVE_FLOOR = 0.7;

/** The pill's glyph, in the frame's own pixels. */
export interface AutoMoveElement {
  readonly at: Point;
  readonly score: number;
}

/**
 * How far from the tapped cell the pill may be drawn. The measured rise is 78 px up and 36 px left;
 * the band keeps room for the map's own scroll and for a pill the game clamps at the panel's edge.
 */
const BAND = { left: 120, right: 120, up: 130, down: 40 } as const;

/**
 * The element a tile tap raised, or null when the tap raised none — the cell has no path. Cheap: one
 * small-band match, run once per walk.
 */
export function findAutoMoveElement(image: RgbaImage, near: Point): AutoMoveElement | null {
  const x = Math.max(0, near.x - BAND.left);
  const y = Math.max(0, near.y - BAND.up);
  const width = Math.min(image.width, near.x + BAND.right) - x;
  const height = Math.min(image.height, near.y + BAND.down) - y;
  if (width < AUTO_MOVE_TEMPLATE.width || height < AUTO_MOVE_TEMPLATE.height) return null;
  const area: PixelRect = { x, y, width, height };
  const match = findTemplate(image, area, AUTO_MOVE_TEMPLATE, { scales: [1], minScore: AUTO_MOVE_FLOOR });
  if (match === null) return null;
  return {
    at: { x: Math.round(match.at.x + match.width / 2), y: Math.round(match.at.y + match.height / 2) },
    score: match.score,
  };
}
