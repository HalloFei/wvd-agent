/**
 * The character page: the menu a party HUD card opens (the one-key heal's first step).
 *
 * Measured 2026-11-03 on `testdata/screens/2026-11-03-character-page/page-1920.jpg`. The page draws a
 * member's name and level at the top, the stat block (HP/MP/SP, 战斗力, 攻击力…), the bottom tab row
 * (关闭 / 强度 / 技能 / 咒文 / 装备 / 背包) and the right-hand key legend. Until now it was `unknown`:
 * the heal opened it and could not see that it was still there, so a swallowed close left the loop on
 * a menu it could not name (live 2026-11-03 03:18 and 03:39 — a 90 s question and a stall, twice).
 *
 * The evidence is its **X 关闭 tile** (61×67 at (683,983) on the frame), template-matched in the bottom
 * band. Measured: 1.000 on the page frame, at most 0.357 on every other 1920×1080 frame recorded (the
 * battle command phases, the 3-D view with its menu legend, a dungeon map, the town, the opener panel,
 * the revive QTE). Floor 0.7.
 *
 * The page is a screen the loop *finishes*: its confidence is the match score, and the World presses
 * the close it names until the page is gone (operator rule 2026-11-03: after open and heal there shall
 * be a close, back to the dungeon).
 */
import type { Frame, Observation, Perceiver, PixelRect, Point, RgbaImage } from '../contracts.ts';
import { CHARACTER_PAGE_TILE_BASE64 } from './character-page-template.ts';
import { findTemplate, type MatchTemplate } from './match.ts';

const REFERENCE_WIDTH = 1920;
const REFERENCE_HEIGHT = 1080;

/** The page's X 关闭 tile at (683,983), 61×67, generated by `scripts/extract-page-template.ts`. */
export const CHARACTER_PAGE_TILE: MatchTemplate = {
  width: 61,
  height: 67,
  gray: Uint8Array.from(Buffer.from(CHARACTER_PAGE_TILE_BASE64, 'base64')),
};

/** The floor the recorded frames support: the page scores 1.000, every other frame at most 0.357. */
export const CHARACTER_PAGE_FLOOR = 0.7;

/** The tile lives in the bottom band of the page; the search is there, not the whole frame. */
const BAND: PixelRect = { x: 560, y: 930, width: 840, height: 150 };

/** Where the tile is on this frame, or null. */
export interface CharacterPageMatch {
  readonly at: Point;
  readonly score: number;
}

/** The page's close tile on this frame, or null. Cheap: one small-band template match. */
export function findCharacterPage(image: RgbaImage): CharacterPageMatch | null {
  if (image.width !== REFERENCE_WIDTH || image.height !== REFERENCE_HEIGHT) return null;
  const match = findTemplate(image, BAND, CHARACTER_PAGE_TILE, { scales: [1], minScore: CHARACTER_PAGE_FLOOR });
  if (match === null) return null;
  return {
    at: { x: Math.round(match.at.x + match.width / 2), y: Math.round(match.at.y + match.height / 2) },
    score: match.score,
  };
}

/** Names the character page; unknown when the close tile is not in the band. */
export class CharacterPagePerceiver implements Perceiver {
  async observe(frame: Frame): Promise<Observation> {
    const unknown: Observation = { screen: 'unknown', atMs: frame.atMs, confidence: 0 };
    let image: RgbaImage;
    try {
      image = await frame.toRgba();
    } catch {
      return unknown;
    }
    const match = findCharacterPage(image);
    if (match === null) return unknown;
    // The tile's own centre is the close target: the World presses the point this reader **matched**,
    // not a fixed coordinate (live 2026-11-09: a fixed point missed and the page stayed).
    return { screen: 'character-page', atMs: frame.atMs, confidence: match.score, at: match.at };
  }
}
