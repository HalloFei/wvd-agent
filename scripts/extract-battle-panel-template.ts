#!/usr/bin/env tsx
/**
 * Generates `src/perception/battle-panel-template.ts` from the live skill-panel frame.
 *
 *   node ../Coopanion/node_modules/tsx/dist/cli.mjs scripts/extract-battle-panel-template.ts
 *
 * The crop is the **確定 button's centre** of the battle's skill panel — 57×33 px centred on
 * (1053, 1006) at 1920×1080, measured live 2026-11-07 22:16 on
 * `testdata/screens/2026-11-07-battle-panel/panel-1920.jpg` (拉巴迪奥斯的秘术, 取消 / 確定). The
 * panel is the same for every skill; what moves between frames is where the game draws it (the same
 * panel measured 2026-11-05 had its buttons at y 975–1035 and this one at 976–1037, so a fixed tap
 * point lands on the panel body and nothing happens). The template is centred on the *button*, so a
 * match's centre is the tap point.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import jpeg from 'jpeg-js';

const SOURCE = 'testdata/screens/2026-11-07-battle-panel/panel-1920.jpg';
const CENTRE = { x: 1053, y: 1006 };
const SIZE = { width: 57, height: 33 };
const OUT = 'src/perception/battle-panel-template.ts';

const image = jpeg.decode(readFileSync(SOURCE), { useTArray: true, formatAsRGBA: true });
const x0 = CENTRE.x - Math.floor(SIZE.width / 2);
const y0 = CENTRE.y - Math.floor(SIZE.height / 2);
const gray = new Uint8Array(SIZE.width * SIZE.height);
for (let y = 0; y < SIZE.height; y += 1) {
  for (let x = 0; x < SIZE.width; x += 1) {
    const i = ((y0 + y) * image.width + (x0 + x)) * 4;
    gray[y * SIZE.width + x] = Math.round(
      0.299 * image.data[i]! + 0.587 * image.data[i + 1]! + 0.114 * image.data[i + 2]!,
    );
  }
}
const base64 = Buffer.from(gray).toString('base64');
writeFileSync(OUT, [
  '/**',
  " * The battle skill panel's 確定 button, " + SIZE.width + 'x' + SIZE.height + ' luma bytes centred on',
  ' * the button (' + CENTRE.x + ',' + CENTRE.y + ') of the frame at `' + SOURCE + '`,',
  " * the live client's own capture (拉巴迪奥斯的秘术, 取消 / 確定, 2026-11-07 22:16). Generated by",
  ' * `scripts/extract-battle-panel-template.ts` — do not edit by hand; re-run the script instead.',
  ' */',
  'export const BATTLE_PANEL_CONFIRM_BASE64 =',
  "  '" + base64 + "';",
  '',
].join('\n'));
console.log('wrote', OUT, 'crop', x0, y0, 'centre', CENTRE);
