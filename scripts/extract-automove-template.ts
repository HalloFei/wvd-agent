#!/usr/bin/env tsx
/**
 * Generates `src/perception/automove-template.ts` from the live frame that carries the 自動移動
 * element. The template is 28x28 luma bytes of the pill's glyph; hand-copying a 1 KB base64 string
 * into a source file lost 161 characters once already (2026-11-02), so the bytes are generated.
 *
 *   node ../Coopanion/node_modules/tsx/dist/cli.mjs scripts/extract-automove-template.ts
 *
 * The crop is the measured glyph box on the frame; if the frame or the UI changes, re-measure the box
 * and update BOX here rather than editing the generated module.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import jpeg from 'jpeg-js';

const SOURCE = 'testdata/nav-2026-11-02-automove/element-over-neighbour-cell.jpg';
const BOX = { x: 1_198, y: 676, width: 28, height: 28 };
const OUT = 'src/perception/automove-template.ts';

const image = jpeg.decode(readFileSync(SOURCE), { useTArray: true, formatAsRGBA: true });
const gray = new Uint8Array(BOX.width * BOX.height);
for (let y = 0; y < BOX.height; y += 1) {
  for (let x = 0; x < BOX.width; x += 1) {
    const i = ((BOX.y + y) * image.width + (BOX.x + x)) * 4;
    gray[y * BOX.width + x] = Math.round(
      0.299 * image.data[i]! + 0.587 * image.data[i + 1]! + 0.114 * image.data[i + 2]!,
    );
  }
}
const base64 = Buffer.from(gray).toString('base64');
const source = [
  '/**',
  ' * The 自動移動 pill\'s glyph, 28x28 luma bytes of the frame at',
  ' * `' + SOURCE + '` (' + BOX.x + ',' + BOX.y + '). Generated by',
  ' * `scripts/extract-automove-template.ts` — do not edit by hand; re-run the script instead.',
  ' */',
  'export const AUTO_MOVE_GLYPH_BASE64 =',
  "  '" + base64 + "';",
  '',
].join('\n');
writeFileSync(OUT, source);
console.log(JSON.stringify({ ok: true, out: OUT, bytes: gray.length, base64: base64.length }));
