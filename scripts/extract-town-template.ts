#!/usr/bin/env tsx
/**
 * Generates `src/perception/town-template.ts` from the live town frame.
 *
 *   node ../Coopanion/node_modules/tsx/dist/cli.mjs scripts/extract-town-template.ts
 *
 * The crop is the **party panel's chevron** at the bottom of the town, measured 2026-11-07 21:14 at
 * 1920×1080 on `testdata/screens/2026-11-07-town-live/town-1920.jpg` (679,789, 34×26). It scores
 * 1.000 on that frame, 0.943–0.956 on the six town frames recorded 2026-10-25, and at most 0.497 on
 * every other 1920×1080 frame in `testdata/` (the search band is `TOWN_PANEL_CHEVRON_BAND` in
 * `location.ts`, at scale 1). The legacy mobile-art template draws the same control at 0.675 and so
 * scores only 0.600 on this frame — the live client redrew the tile, which is why this sample exists.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import jpeg from 'jpeg-js';

const SOURCE = 'testdata/screens/2026-11-07-town-live/town-1920.jpg';
const BOX = { x: 679, y: 789, width: 34, height: 26 };
const OUT = 'src/perception/town-template.ts';

const image = jpeg.decode(readFileSync(SOURCE), { useTArray: true, formatAsRGBA: true });
const gray = new Uint8Array(BOX.width * BOX.height);
for (let y = 0; y < BOX.height; y += 1) {
  for (let x = 0; x < BOX.width; x += 1) {
    const i = ((BOX.y + y) * image.width + (BOX.x + x)) * 4;
    gray[y * BOX.width + x] = Math.round(
      0.299 * image.data[i]! + 0.587 * image.data[i + 1]! + 0.114 * image.data[i + 2]!,
    );
  }
}
const base64 = Buffer.from(gray).toString('base64');
writeFileSync(OUT, [
  '/**',
  ' * The town party panel\'s chevron, 34x26 luma bytes of the frame at',
  ' * `' + SOURCE + '` (' + BOX.x + ',' + BOX.y + '), the live client\'s own capture. Generated by',
  ' * `scripts/extract-town-template.ts` — do not edit by hand; re-run the script instead.',
  ' */',
  'export const TOWN_PANEL_CHEVRON_BASE64 =',
  "  '" + base64 + "';",
  '',
].join('\n'));
console.log(JSON.stringify({ ok: true, out: OUT, bytes: gray.length }));
