#!/usr/bin/env tsx
/**
 * Generates src/perception/inn-library.ts — the measured label library for the rest town's inn.
 *
 *   node ../Coopanion/node_modules/tsx/dist/cli.mjs scripts/extract-inn-labels.ts
 *
 * Measured 2026-11-06 on two recorded frames:
 *
 * - the service menu (inn-service-1920.jpg, the innkeeper's dialog): 住宿 / 对话 / 离开;
 * - the room list (inn-rooms-1280.jpg, the 旅店 dialog after 住宿): 马房 / 标准房 / 返回.
 *
 * The rows are game UI: a label on a light button, and a room row carries a price on the right
 * (0G, 200G) that the label band leaves out. The row centres below are the measured text lines; the
 * reader re-samples each frame into the same grid, so one entry serves 1280 and 1920.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import jpeg from 'jpeg-js';
import { sampleRegion } from '../src/perception/reader.ts';

const OUT = 'src/perception/inn-library.ts';

/** The label band: x 0.50..0.615 of the width, plus/minus 0.014 of the height around the text line. */
export const INN_BAND = { x0: 0.5, x1: 0.615 } as const;
export const INN_ROW_HALF_HEIGHT = 0.014;
const PATCH = { width: 240, height: 26 };

/** The rows measured on the two recordings: label, frame, and the text line's centre as a fraction. */
const ROWS = [
  { label: '住宿', source: 'testdata/screens/2026-11-06-inn/inn-service-1920.jpg', centre: 488 / 1_080 },
  { label: '对话', source: 'testdata/screens/2026-11-06-inn/inn-service-1920.jpg', centre: 578 / 1_080 },
  { label: '离开', source: 'testdata/screens/2026-11-06-inn/inn-service-1920.jpg', centre: 641 / 1_080 },
  { label: '马房', source: 'testdata/screens/2026-11-06-inn/inn-rooms-1280.jpg', centre: 366 / 720 },
  { label: '标准房', source: 'testdata/screens/2026-11-06-inn/inn-rooms-1280.jpg', centre: 404 / 720 },
  { label: '返回', source: 'testdata/screens/2026-11-06-inn/inn-rooms-1280.jpg', centre: 441 / 720 },
];

const decoded = new Map();
const entries = ROWS.map((row) => {
  let image = decoded.get(row.source);
  if (image === undefined) {
    image = jpeg.decode(readFileSync(row.source), { useTArray: true, formatAsRGBA: true });
    decoded.set(row.source, image);
  }
  const region = {
    x0: INN_BAND.x0,
    y0: row.centre - INN_ROW_HALF_HEIGHT,
    x1: INN_BAND.x1,
    y1: row.centre + INN_ROW_HALF_HEIGHT,
  };
  const patch = sampleRegion(image, region, PATCH.width, PATCH.height);
  return { label: row.label, width: patch.width, height: patch.height, gray: patch.gray };
});

const lines = [
  '/**',
  " * The inn's label library, measured 2026-11-06 on the two recordings: the service menu's",
  " * 住宿 / 对话 / 离开 (inn-service-1920.jpg) and the room list's 马房 / 标准房 / 返回",
  ' * (inn-rooms-1280.jpg). Generated by scripts/extract-inn-labels.ts — do not edit by hand;',
  ' * re-run it when a new row is recorded (a room the inn starts offering is one more entry).',
  ' */',
  "import type { LibraryEntry } from './reader.ts';",
  '',
  'export const INN_ROW_LABELS: readonly LibraryEntry[] = [',
  ...entries.flatMap((entry) => [
    '  {',
    "    label: '" + entry.label + "',",
    '    width: ' + entry.width + ',',
    '    height: ' + entry.height + ',',
    "    gray: Uint8Array.from(Buffer.from('" + Buffer.from(entry.gray).toString('base64') + "', 'base64')),",
    '  },',
  ]),
  '];',
  '',
].join('\n');
writeFileSync(OUT, lines);
console.log(JSON.stringify({ ok: true, out: OUT, entries: entries.map((entry) => entry.label), bytes: lines.length }));
