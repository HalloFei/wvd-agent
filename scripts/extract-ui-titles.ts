#!/usr/bin/env tsx
/**
 * Generates src/ui/library.ts - the title band of every page the reader can name.
 *
 *   node ../Coopanion/node_modules/tsx/dist/cli.mjs scripts/extract-ui-titles.ts
 *
 * A page is recognised by the title it draws (选项, 记录, 每日任务, ...), which is the one line of text
 * every one of these overlays carries and the game does not vary. The band is a fraction of the frame,
 * sampled into a fixed grid, so the same entry reads a 1280 still and the 1920 live client alike -
 * the measure is the reader's (`sampleRegion`, `correlation`), the same one the inn's rows use.
 *
 * The script prints the self/cross matrix it measured, which is where the perceiver's floor comes from:
 * a page must answer its own still far above every other page's.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import jpeg from 'jpeg-js';
import { correlation, sampleRegion, type ReadRegion } from '../src/perception/reader.ts';

const OUT = 'src/ui/library.ts';
const GRID = { width: 192, height: 24 };
const DIR = 'testdata/screens/2026-11-06-ui/';

/** The page id, the still it was measured on, and its title band as fractions of the frame. */
const TITLES: readonly { readonly page: string; readonly source: string; readonly region: ReadRegion }[] = [
  { page: 'options', source: DIR + 'options-1280.jpg', region: { x0: 0.455, y0: 0.070, x1: 0.545, y1: 0.120 } },
  { page: 'records', source: DIR + 'records-1280.jpg', region: { x0: 0.4625, y0: 0.111, x1: 0.5375, y1: 0.161 } },
  { page: 'missions', source: DIR + 'missions-1280.jpg', region: { x0: 0.45, y0: 0.062, x1: 0.55, y1: 0.132 } },
  { page: 'inventory', source: DIR + 'inventory-1280.jpg', region: { x0: 0.452, y0: 0.048, x1: 0.548, y1: 0.098 } },
  { page: 'shop', source: DIR + 'shop-items-1280.jpg', region: { x0: 0.455, y0: 0.025, x1: 0.545, y1: 0.070 } },
  { page: 'temple', source: DIR + 'temple-1280.jpg', region: { x0: 0.46, y0: 0.035, x1: 0.54, y1: 0.080 } },
  { page: 'trader', source: DIR + 'trader-1280.jpg', region: { x0: 0.455, y0: 0.035, x1: 0.545, y1: 0.080 } },
  { page: 'blessed-day', source: DIR + 'blessed-day-1280.jpg', region: { x0: 0.45, y0: 0.183, x1: 0.55, y1: 0.235 } },
];

interface RgbaImage { readonly data: Uint8Array; readonly width: number; readonly height: number }
const decoded = new Map<string, RgbaImage>();
function image(path: string): RgbaImage {
  const cached = decoded.get(path);
  if (cached !== undefined) return cached;
  const raw = jpeg.decode(readFileSync(path), { useTArray: true, formatAsRGBA: true });
  const made: RgbaImage = { data: raw.data, width: raw.width, height: raw.height };
  decoded.set(path, made);
  return made;
}

const entries = TITLES.map(({ page, source, region }) => ({
  page,
  region,
  ...sampleRegion(image(source), region, GRID.width, GRID.height),
}));

// The self/cross matrix: every entry against every still, so the floor is a measurement.
const rows = TITLES.map(({ page, source }) => {
  const still = image(source);
  const scored = entries
    .map((entry) => ({ page: entry.page, score: correlation(sampleRegion(still, entry.region, GRID.width, GRID.height), entry) }))
    .sort((a, b) => b.score - a.score);
  return { page, self: scored.find((item) => item.page === page)!.score, best: scored[0]!, second: scored[1]! };
});

const lines = [
  '/**',
  ' * The pages the reader can name, by the title they draw. Measured 2026-11-06 on the stills in',
  ' * testdata/screens/2026-11-06-ui/, one title band per page, sampled into a fixed grid so the entry',
  ' * reads any 16:9 frame size. Generated by scripts/extract-ui-titles.ts - do not edit by hand;',
  ' * re-run it when a page is recorded (a new page is one more line in that script).',
  ' */',
  "import type { ReadRegion } from '../perception/reader.ts';",
  '',
  '/** One page title: the band it was sampled in, and the luma the band carried. */',
  'export interface UiTitleEntry {',
  '  readonly page: string;',
  '  readonly region: ReadRegion;',
  '  readonly width: number;',
  '  readonly height: number;',
  '  readonly gray: Uint8Array;',
  '}',
  '',
  'export const UI_TITLES: readonly UiTitleEntry[] = [',
  ...entries.flatMap((entry) => [
    '  {',
    "    page: '" + entry.page + "',",
    '    region: {',
    '      x0: ' + entry.region.x0 + ', y0: ' + entry.region.y0 + ',',
    '      x1: ' + entry.region.x1 + ', y1: ' + entry.region.y1 + ',',
    '    },',
    '    width: ' + entry.width + ', height: ' + entry.height + ',',
    "    gray: Uint8Array.from(Buffer.from('" + Buffer.from(entry.gray).toString('base64') + "', 'base64')),",
    '  },',
  ]),
  '];',
  '',
].join('\n');
writeFileSync(OUT, lines);
console.log(JSON.stringify({ ok: true, out: OUT, bytes: lines.length, matrix: rows }, null, 0));
