#!/usr/bin/env tsx
/**
 * Generates `src/perception/quick-heal-template.ts` from the live 一键恢复 dialog frame.
 *
 *   node ../Coopanion/node_modules/tsx/dist/cli.mjs scripts/extract-quick-heal-template.ts
 *
 * The dialog draws two gold-plated buttons side by side — 关闭 (left) and 恢复 (right) — at
 * y ≈ 774-830 on the 1920×1080 client. Both crops are templates: the dialog is named only when
 * **both** match at their measured places, which no other measured page does.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import jpeg from 'jpeg-js';

const SOURCE = 'testdata/screens/2026-11-09-heal/quick-heal-1920.jpg';
const RESTORE = { x: 1005, y: 774, width: 165, height: 56 };
const CANCEL = { x: 767, y: 774, width: 165, height: 56 };
const OUT = 'src/perception/quick-heal-template.ts';

const image = jpeg.decode(readFileSync(SOURCE), { useTArray: true, formatAsRGBA: true });

const crop = (box: { x: number; y: number; width: number; height: number }): string => {
  const gray = new Uint8Array(box.width * box.height);
  for (let y = 0; y < box.height; y += 1) {
    for (let x = 0; x < box.width; x += 1) {
      const i = ((box.y + y) * image.width + (box.x + x)) * 4;
      gray[y * box.width + x] = Math.round(
        0.299 * image.data[i]! + 0.587 * image.data[i + 1]! + 0.114 * image.data[i + 2]!,
      );
    }
  }
  return Buffer.from(gray).toString('base64');
};

const box = (value: { x: number; y: number; width: number; height: number }): string =>
  JSON.stringify(value).replaceAll('"', '');

writeFileSync(OUT, [
  '/**',
  ' * The 一键恢复 dialog\'s two button plates, cropped from',
  ' * `' + SOURCE + '` (measured 2026-11-09). Generated by',
  ' * `scripts/extract-quick-heal-template.ts` — do not edit by hand; re-run the script instead.',
  ' */',
  'export const QUICK_HEAL_RESTORE = {',
  '  box: ' + box(RESTORE) + ',',
  "  grayBase64: '" + crop(RESTORE) + "',",
  '} as const;',
  'export const QUICK_HEAL_CANCEL = {',
  '  box: ' + box(CANCEL) + ',',
  "  grayBase64: '" + crop(CANCEL) + "',",
  '} as const;',
  '',
].join('\n'));
console.log(JSON.stringify({ ok: true, out: OUT }));
