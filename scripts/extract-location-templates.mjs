#!/usr/bin/env node
/**
 * Provenance for the location templates in `src/perception/location-templates.ts`.
 *
 * Not part of CI: it reads the study checkout `../wvd/resources/images` and needs `ffmpeg` and
 * `ffprobe` on PATH. Node has no PNG/WebP decoder and adding one is forbidden (the map-template
 * script's rule), so the decode goes through ffmpeg's rawvideo pipe. The output is the legacy mobile
 * art, grayscale, at its native size; `src/perception/match.ts` rescales it to the PC UI's 0.675.
 *
 *   node scripts/extract-location-templates.mjs > src/perception/location-templates.ts
 *
 * The sources are the files the legacy script matched (contracts §5 of the design): the world-map
 * control, the party-panel chevron, the inn label, the four city nodes, 诺森霍洛村, 北穿幽冥城 and
 * the three FFXI dungeon-select rows. `City_DHI` and `City_fortress` are included for the catalog
 * but no committed frame carries them yet.
 */
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const IMAGES = fileURLToPath(new URL('../../wvd/resources/images/', import.meta.url));

const SOURCES = [
  ['world-map-icon', 'common/intoWorldMap.png'],
  ['panel-chevron', 'common/closePartyInfo.png'],
  ['inn', 'zh_CN/Inn.png'],
  ['city-royal', 'zh_CN/City_RoyalCityLuknalia.png'],
  ['city-port', 'zh_CN/City_portTownGrandLegion.png'],
  ['city-dhi', 'zh_CN/City_DHI.png'],
  ['city-fortress', 'zh_CN/City_fortress.png'],
  ['vnh', 'zh_CN/FFXI/City_VNH.png'],
  ['ffxi-gcn', 'zh_CN/FFXI/GCN.png'],
  ['ffxi-zone1', 'zh_CN/FFXI/ZONE1.png'],
  ['ffxi-zone2', 'zh_CN/FFXI/ZONE2.png'],
  ['ffxi-zone3', 'zh_CN/FFXI/ZONE3.png'],
];

function probe(path) {
  const [width, height] = execFileSync(
    'ffprobe',
    ['-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height', '-of', 'csv=p=0', path],
    { encoding: 'utf8' },
  ).trim().split(',').map(Number);
  if (!Number.isInteger(width) || !Number.isInteger(height) || width <= 0 || height <= 0) {
    throw new Error(`${path}: ffprobe returned ${width}x${height}`);
  }
  return { width, height };
}

function decodeGray(path) {
  const { width, height } = probe(path);
  const raw = execFileSync('ffmpeg', ['-v', 'error', '-i', path, '-f', 'rawvideo', '-pix_fmt', 'gray', '-'], {
    maxBuffer: 256 * 1024 * 1024,
  });
  if (raw.length !== width * height) {
    throw new Error(`${path}: ffmpeg returned ${raw.length} bytes, expected ${width * height}`);
  }
  return { width, height, gray: raw.toString('base64') };
}

const entries = SOURCES.map(([id, source]) => {
  const path = IMAGES + source;
  return `  '${id}': { source: '${source}', ...${JSON.stringify(decodeGray(path))} },`;
});

process.stdout.write(
  `// Generated by scripts/extract-location-templates.mjs. Do not edit by hand.\n` +
  `// Each entry is the legacy mobile art in grayscale at its native size; the matcher rescales it.\n` +
  `export interface RawTemplate {\n` +
  `  readonly source: string;\n  readonly width: number;\n  readonly height: number;\n` +
  `  readonly gray: string;   // base64 of width*height 8-bit luma\n}\n\n` +
  `export const RAW_TEMPLATES: Readonly<Record<string, RawTemplate>> = {\n` +
  entries.join('\n') +
  `\n};\n`,
);
