#!/usr/bin/env tsx
/**
 * Generates src/perception/drops.ts - the chest drops the World can name, by the caption the game
 * draws when the chest gives them (獲得了 <item>！！).
 *
 *   node ../Coopanion/node_modules/tsx/dist/cli.mjs scripts/extract-drop-items.ts
 *
 * The operator's rule (2026-11-06): a drop the World has never seen is named **after the game's own
 * line** and recorded, instead of staying an unknown screen that stalls the farm. The runtime cannot
 * read the text, so the recording is this table: one line per recorded drop, the caption band sampled
 * from its frame into a fixed grid, exactly as the inn's rows and the pages' titles are.
 *
 * It prints the self/cross matrix the reader's floor comes from.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import jpeg from 'jpeg-js';
import { correlation, sampleRegion, type ReadRegion } from '../src/perception/reader.ts';

const OUT = 'src/perception/drops.ts';
const GRID = { width: 240, height: 28 };

/** The caption line's band: measured ink at x 0.381-0.547, y 0.806-0.824 on the 1920 frames. */
const CAPTION: ReadRegion = { x0: 0.37, y0: 0.795, x1: 0.56, y1: 0.835 };

/** One recorded drop: the name the game draws, and the frame it was read from. */
const DROPS: readonly { readonly item: string; readonly source: string }[] = [
  {
    item: '10,000拜恩纸币',
    source: 'testdata/screens/2026-11-06-loot-currency/loot-currency-1920.jpeg',
  },
];

interface RgbaImage { readonly data: Uint8Array; readonly width: number; readonly height: number }
const decoded = new Map<string, RgbaImage>();
function image(path: string): RgbaImage {
  const cached = decoded.get(path);
  if (cached !== undefined) return cached;
  const raw = jpeg.decode(readFileSync(path), { useTArray: true, formatAsRGBA: true });
  const made: RgbaImage = { data: raw.data, width: raw.width, height: raw.height };
  decoded.set(path, made);
  return made;
}

const entries = DROPS.map(({ item, source }) => ({
  item,
  region: CAPTION,
  ...sampleRegion(image(source), CAPTION, GRID.width, GRID.height),
}));

// The self/cross matrix, over every recorded frame: the floor is a measurement, not a guess.
const matrix = DROPS.map(({ source }) => {
  const still = image(source);
  const scored = entries
    .map((entry) => ({ item: entry.item, score: correlation(sampleRegion(still, entry.region, GRID.width, GRID.height), entry) }))
    .sort((a, b) => b.score - a.score);
  return { source: source.split('/').slice(-1)[0], best: scored[0], second: scored[1] ?? null };
});

const lines = [
  '/**',
  ' * The chest drops the World can name, by the line the game draws when the chest gives them.',
  ' * Measured 2026-11-06 on the committed currency frames; generated by',
  ' * scripts/extract-drop-items.ts - do not edit by hand. A new drop is one more line in that script:',
  ' * read the name off the frame, run it, and commit the frame and the library together.',
  ' */',
  "import type { ReadRegion } from './reader.ts';",
  '',
  '/** One recorded drop: the name the game draws, the caption band, and the ink it carried. */',
  'export interface DropEntry {',
  '  readonly item: string;',
  '  readonly region: ReadRegion;',
  '  readonly width: number;',
  '  readonly height: number;',
  '  readonly gray: Uint8Array;',
  '}',
  '',
  'export const DROP_ITEMS: readonly DropEntry[] = [',
  ...entries.flatMap((entry) => [
    '  {',
    "    item: '" + entry.item + "',",
    '    region: {',
    '      x0: ' + entry.region.x0 + ', y0: ' + entry.region.y0 + ',',
    '      x1: ' + entry.region.x1 + ', y1: ' + entry.region.y1 + ',',
    '    },',
    '    width: ' + entry.width + ', height: ' + entry.height + ',',
    "    gray: Uint8Array.from(Buffer.from('" + Buffer.from(entry.gray).toString('base64') + "', 'base64')),",
    '  },',
  ]),
  '];',
  '',
].join('\n');
writeFileSync(OUT, lines);
console.log(JSON.stringify({ ok: true, out: OUT, bytes: lines.length, matrix }, null, 0));
