#!/usr/bin/env tsx
/**
 * Generates `src/perception/harken-library.ts` — the measured label library for the harken's floor
 * menu — from the live frame.
 *
 *   node ../Coopanion/node_modules/tsx/dist/cli.mjs scripts/extract-harken-labels.ts
 *
 * The labels were read by the operator off the frame (2026-11-03): the harken at 第三区-城内2F offers
 * 第一区-城外-, 第二区-城内1F-, 第四区-城内2F深处- and 归还. The list is **not fixed** — a harken only
 * offers a floor once that floor's harken has been reconstructed — so this is a library, not a layout:
 * the reader matches rows against it and reports `null` for a label it has never seen.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import jpeg from 'jpeg-js';
import { sampleRegion } from '../src/perception/reader.ts';

const SOURCE = 'testdata/screens/2026-11-03-harken-menu/harken-2f.jpg';
const OUT = 'src/perception/harken-library.ts';

/** The rows measured on this frame: label, and the label band's centre as a fraction of the height. */
const ROWS = [
  { label: '第一区-城外-', centre: 484 / 1_080 },
  { label: '第二区-城内1F-', centre: 556 / 1_080 },
  { label: '第四区-城内2F深处-', centre: 628 / 1_080 },
  { label: '归还', centre: 700 / 1_080 },
];
/** The label band: x 0.43..0.57 of the width, ±0.013 of the height around the row's centre. */
const BAND = { x0: 0.43, x1: 0.57 };
const HALF_HEIGHT = 0.013;
/** The sampled grid every entry carries; readers resample their frame into the same grid. */
const PATCH = { width: 240, height: 26 };

const decoded = jpeg.decode(readFileSync(SOURCE), { useTArray: true, formatAsRGBA: true });
const image = { data: decoded.data, width: decoded.width, height: decoded.height };

const entries = ROWS.map((row) => {
  const region = { x0: BAND.x0, y0: row.centre - HALF_HEIGHT, x1: BAND.x1, y1: row.centre + HALF_HEIGHT };
  const patch = sampleRegion(image, region, PATCH.width, PATCH.height);
  return { label: row.label, ...patch };
});

const lines = [
  '/**',
  ' * The harken floor menu\'s label library, measured on',
  ' * `' + SOURCE + '` (2026-11-03): 第一区-城外-, 第二区-城内1F-, 第四区-城内2F深处-, 归还.',
  ' * Generated by `scripts/extract-harken-labels.ts` — do not edit by hand; re-run the script when a',
  ' * new label is measured (the list is not fixed: a harken offers a floor only once it is reconstructed).',
  ' */',
  "import type { LibraryEntry } from './reader.ts';",
  '',
  'export const HARKEN_ROW_LABELS: readonly LibraryEntry[] = [',
  ...entries.flatMap((entry) => [
    '  {',
    "    label: '" + entry.label + "',",
    '    width: ' + entry.width + ',',
    '    height: ' + entry.height + ',',
    "    gray: Uint8Array.from(Buffer.from('" + Buffer.from(entry.gray).toString('base64') + "', 'base64')),",
    '  },',
  ]),
  '];',
  '',
].join('\n');
writeFileSync(OUT, lines);
console.log(JSON.stringify({ ok: true, out: OUT, entries: entries.length, bytes: lines.length }));
