#!/usr/bin/env node
/**
 * Provenance for the world-map atlas image in `src/perception/worldmap-atlas-image.ts`.
 *
 * The atlas is the committed stitch `testdata/worldmap/2026-11-01/overview-full.jpg`, 1360x1496
 * atlas pixels (see docs/status.md, "The world map, stored"). The registration localiser
 * (src/perception/map-localiser.ts) needs the whole map as one luma image: the stored copy is
 * box-averaged 2x1 to 680x748 so the generated module stays under a megabyte, and every match is
 * refined against that grid (2 atlas px per stored px).
 *
 *   node scripts/extract-worldmap-atlas.mjs > src/perception/worldmap-atlas-image.ts
 *
 * The sha256 is recorded so a re-stitch of the atlas is provably a new input.
 */
import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const file = new URL('../testdata/worldmap/2026-11-01/overview-full.jpg', import.meta.url);
const ATLAS_WIDTH = 1360;
const ATLAS_HEIGHT = 1496;
/** Stored resolution: one stored pixel is this many atlas pixels. */
const DOWN = 2;

const path = file.pathname.replace(/^\/([A-Za-z]:)/, '$1');
const raw = execFileSync(
  'ffmpeg',
  ['-v', 'error', '-i', path, '-f', 'rawvideo', '-pix_fmt', 'gray', '-'],
  { maxBuffer: 256 * 1024 * 1024 },
);
if (raw.length !== ATLAS_WIDTH * ATLAS_HEIGHT) {
  throw new Error('atlas: ' + raw.length + ' bytes, expected ' + ATLAS_WIDTH * ATLAS_HEIGHT);
}
const width = ATLAS_WIDTH / DOWN;
const height = ATLAS_HEIGHT / DOWN;
const gray = Buffer.alloc(width * height);
for (let y = 0; y < height; y += 1) {
  for (let x = 0; x < width; x += 1) {
    let sum = 0;
    for (let row = 0; row < DOWN; row += 1) {
      for (let column = 0; column < DOWN; column += 1) {
        sum += raw[(y * DOWN + row) * ATLAS_WIDTH + x * DOWN + column];
      }
    }
    gray[y * width + x] = Math.round(sum / (DOWN * DOWN));
  }
}
const sha = createHash('sha256').update(readFileSync(path)).digest('hex');
const lines = [
  '// Generated by scripts/extract-worldmap-atlas.mjs. Do not edit by hand.',
  '// The stitched world map as one luma image: ' + ATLAS_WIDTH + 'x' + ATLAS_HEIGHT + ' atlas px,',
  '// stored box-averaged ' + DOWN + 'x at ' + width + 'x' + height + ' (1 stored px = ' + DOWN + ' atlas px).',
  '// Source: testdata/worldmap/2026-11-01/overview-full.jpg sha256 ' + sha,
  'export const WORLD_MAP_ATLAS_IMAGE = {',
  '  /** The atlas size in atlas pixels. */',
  '  atlasWidth: ' + ATLAS_WIDTH + ',',
  '  atlasHeight: ' + ATLAS_HEIGHT + ',',
  '  /** Stored pixels per atlas pixel. */',
  '  pixelsPerCell: ' + DOWN + ',',
  '  /** Stored image size. */',
  '  width: ' + width + ',',
  '  height: ' + height + ',',
  '  /** base64 of width*height 8-bit luma. */',
  '  gray:',
  '    ' + JSON.stringify(gray.toString('base64')) + ',',
  '} as const;',
  '',
];
process.stdout.write(lines.join('\n'));
