#!/usr/bin/env node
/**
 * Provenance for the world-map label templates in `src/perception/worldmap-labels.ts`.
 *
 * The labels are screen-space art: the same banner at every zoom, so a crop from the stitched
 * max-zoom-out atlas matches a live frame unchanged. Localisation needs two of them: each matched
 * banner names a known atlas point, and one point is enough for a translation at max-out.
 *
 *   node scripts/extract-worldmap-labels.mjs > src/perception/worldmap-labels.ts
 *
 * The atlas is the committed stitch `testdata/worldmap/2026-11-01/overview.jpg`; the boxes are the
 * banner rectangles measured on it (see docs/status.md, 2026-11-01).
 */
import { readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';

const atlas = new URL('../testdata/worldmap/2026-11-01/overview.jpg', import.meta.url);
const ATLAS_WIDTH = 1469;
const ATLAS_HEIGHT = 1080;
/** Banner rectangles measured on the atlas, in atlas pixels: { id: [x, y, w, h] }. */
const BOXES = [
  ['vnh', 567, 439, 153, 34],
  ['ancient-shrine', 569, 567, 186, 36],
  ['varian-plain', 213, 610, 172, 35],
  ['city-royal', 492, 730, 168, 33],
  ['guard-fortress', 741, 765, 153, 34],
  ['black-plum-pavilion', 528, 835, 174, 35],
  ['red-sand-bastion', 888, 697, 178, 35],
];

const path = atlas.pathname.replace(/^\/([A-Za-z]:)/, '$1');
const width = ATLAS_WIDTH;
const height = ATLAS_HEIGHT;
const raw = execFileSync(
  'ffmpeg',
  ['-v', 'error', '-i', path, '-f', 'rawvideo', '-pix_fmt', 'gray', '-'],
  { maxBuffer: 256 * 1024 * 1024 },
);
if (raw.length !== width * height) throw new Error('atlas: ' + raw.length + ' bytes, expected ' + width * height);

const entries = BOXES.map(([id, x, y, w, h]) => {
  const gray = Buffer.alloc(w * h);
  for (let row = 0; row < h; row++) {
    raw.copy(gray, row * w, (y + row) * width + x, (y + row) * width + x + w);
  }
  return '  ' + JSON.stringify(id) + ': { width: ' + w + ', height: ' + h + ', at: { x: ' + x + ', y: ' + y + ' }, gray: ' +
    JSON.stringify(gray.toString('base64')) + ' },';
});

process.stdout.write(
  '// Generated by scripts/extract-worldmap-labels.mjs. Do not edit by hand.\n' +
  '// Each entry is a label banner cropped from the max-zoom-out atlas, in grayscale at its drawn size.\n' +
  'export interface WorldMapLabel {\n' +
  '  readonly width: number;\n  readonly height: number;\n' +
  '  /** The banner\'s top-left in atlas pixels. */\n  readonly at: { readonly x: number; readonly y: number };\n' +
  '  /** base64 of width*height 8-bit luma. */\n  readonly gray: string;\n}\n\n' +
  'export const WORLD_MAP_LABELS: Readonly<Record<string, WorldMapLabel>> = {\n' +
  entries.join('\n') + '\n};\n',
);
