#!/usr/bin/env tsx
/**
 * Generates `src/perception/character-page-template.ts` from the live character page frame.
 *
 *   node ../Coopanion/node_modules/tsx/dist/cli.mjs scripts/extract-page-template.ts
 *
 * The crop is the **X 关闭 tile** at the bottom-left of the page's tab row (measured 2026-11-03 at
 * 1920×1080 on `testdata/screens/2026-11-03-character-page/page-1920.jpg`). It scores 1.000 on that
 * frame and at most 0.357 on every non-page frame measured, so it is the page's own evidence.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import jpeg from 'jpeg-js';

const SOURCE = 'testdata/screens/2026-11-03-character-page/page-1920.jpg';
const BOX = { x: 683, y: 983, width: 61, height: 67 };
const OUT = 'src/perception/character-page-template.ts';

const image = jpeg.decode(readFileSync(SOURCE), { useTArray: true, formatAsRGBA: true });
const gray = new Uint8Array(BOX.width * BOX.height);
for (let y = 0; y < BOX.height; y += 1) {
  for (let x = 0; x < BOX.width; x += 1) {
    const i = ((BOX.y + y) * image.width + (BOX.x + x)) * 4;
    gray[y * BOX.width + x] = Math.round(
      0.299 * image.data[i]! + 0.587 * image.data[i + 1]! + 0.114 * image.data[i + 2]!,
    );
  }
}
const base64 = Buffer.from(gray).toString('base64');
writeFileSync(OUT, [
  '/**',
  ' * The character page\'s X 关闭 tile, 61x67 luma bytes of the frame at',
  ' * `' + SOURCE + '` (' + BOX.x + ',' + BOX.y + '). Generated by',
  ' * `scripts/extract-page-template.ts` — do not edit by hand; re-run the script instead.',
  ' */',
  'export const CHARACTER_PAGE_TILE_BASE64 =',
  "  '" + base64 + "';",
  '',
].join('\n'));
console.log(JSON.stringify({ ok: true, out: OUT, bytes: gray.length }));
